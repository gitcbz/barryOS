//! 8x16 bitmap font for text rendering on the framebuffer.
//!
//! Each character occupies an 8x16 cell, stored as 16 bytes — one byte per
//! scanline, MSB = leftmost pixel.  This is the classic VGA/BIOS 8x16 face.
//!
//! The previous revision only filled in the first 7 scanlines of every glyph
//! and left the remaining 9 zeroed, so text rendered at half height with a
//! blank band underneath it; seven glyphs (`% & ? @ \ _ `` `) were blank
//! entirely.  The whole table is now 16 scanlines per glyph.

use crate::dev::framebuffer;
use crate::serial;

/// Cell size.  Every layout constant in the window manager assumes these.
pub const GLYPH_WIDTH: u32 = 8;
pub const GLYPH_HEIGHT: u32 = 16;

/// Draw a character at pixel position (x, y) with color (r,g,b).
pub fn draw_char(ch: u8, x: u32, y: u32, r: u8, g: u8, b: u8) {
    if ch < 32 || ch > 126 {
        return;
    }
    let glyph = &FONT_DATA[(ch - 32) as usize];
    for (row, &bits) in glyph.iter().enumerate() {
        if bits == 0 {
            continue;
        }
        for col in 0..GLYPH_WIDTH {
            if bits & (0x80 >> col) != 0 {
                framebuffer::put_pixel(x + col, y + row as u32, r, g, b);
            }
        }
    }
}

/// Draw a string at pixel position (x, y).
pub fn draw_str(text: &str, x: u32, y: u32, r: u8, g: u8, b: u8) {
    let mut cx = x;
    for &ch in text.as_bytes() {
        draw_char(ch, cx, y, r, g, b);
        cx += GLYPH_WIDTH;
    }
}

/// Draw a string at pixel position (x, y), scaled by an integer factor.
///
/// Integer only: a fractional scale would resample the bitmap and smear it.
/// Used for the boot splash and login title, which need to read as headlines
/// rather than as 8x16 console text.
pub fn draw_str_scaled(text: &str, x: u32, y: u32, scale: u32, r: u8, g: u8, b: u8) {
    if scale <= 1 {
        draw_str(text, x, y, r, g, b);
        return;
    }
    let mut cx = x;
    for &ch in text.as_bytes() {
        if ch >= 32 && ch <= 126 {
            let glyph = &FONT_DATA[(ch - 32) as usize];
            for (row, &bits) in glyph.iter().enumerate() {
                if bits == 0 {
                    continue;
                }
                let mut col = 0u32;
                while col < GLYPH_WIDTH {
                    if bits & (0x80 >> col) != 0 {
                        // Run-length the lit pixels: one fill_rect per run
                        // instead of one per pixel.
                        let start = col;
                        while col < GLYPH_WIDTH && bits & (0x80 >> col) != 0 {
                            col += 1;
                        }
                        framebuffer::fill_rect(
                            cx + start * scale,
                            y + (row as u32) * scale,
                            (col - start) * scale,
                            scale,
                            r, g, b,
                        );
                    } else {
                        col += 1;
                    }
                }
            }
        }
        cx += GLYPH_WIDTH * scale;
    }
}

/// Width in pixels of `text` at the given scale.
pub fn text_width(text: &str, scale: u32) -> u32 {
    (text.len() as u32) * GLYPH_WIDTH * scale
}

/// Draw a string over a filled background (for readability).
pub fn draw_str_bg(text: &str, x: u32, y: u32, fr: u8, fg: u8, fb: u8, br: u8, bg_: u8, bb: u8) {
    let w = (text.len() as u32) * GLYPH_WIDTH;
    framebuffer::fill_rect(x, y, w, GLYPH_HEIGHT, br, bg_, bb);
    draw_str(text, x, y, fr, fg, fb);
}

pub fn init() {
    serial::print_str("[font] 8x16 bitmap font initialized (");
    serial::print_hex(FONT_DATA.len() as u64);
    serial::print_str(" glyphs, 16 scanlines each)\n");
}

