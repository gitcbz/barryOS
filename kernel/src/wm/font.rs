//! 8x16 bitmap font for text rendering on the framebuffer.
//!
//! Each character is 8 pixels wide, 16 pixels tall, stored as 16 bytes
//! (one byte per row, MSB = leftmost pixel).  We include a minimal
//! printable ASCII set (32..127) covering letters, digits, punctuation.

use crate::dev::framebuffer;
use crate::serial;

/// Font data: 96 printable ASCII characters (32..127), each 16 bytes.
/// Total: 96 * 16 = 1536 bytes.
/// This is a compact, readable monospace font (based on the classic
/// 8x16 VGA font, condensed to essential glyphs).
const GLYPH_HEIGHT: usize = 16;
const GLYPH_WIDTH: usize = 8;

/// Draw a character at pixel position (x, y) with color (r,g,b).
pub fn draw_char(ch: u8, x: u32, y: u32, r: u8, g: u8, b: u8) {
    if ch < 32 || ch > 126 {
        return;
    }
    let glyph_idx = (ch - 32) as usize;
    let glyph = &FONT_DATA[glyph_idx];
    for row in 0..GLYPH_HEIGHT {
        let bits = glyph[row];
        for col in 0..GLYPH_WIDTH {
            if bits & (0x80 >> col) != 0 {
                framebuffer::put_pixel(x + col as u32, y + row as u32, r, g, b);
            }
        }
    }
}

/// Draw a string at pixel position (x, y).
pub fn draw_str(text: &str, x: u32, y: u32, r: u8, g: u8, b: u8) {
    let mut cx = x;
    for &ch in text.as_bytes() {
        draw_char(ch, cx, y, r, g, b);
        cx += GLYPH_WIDTH as u32;
    }
}

/// Draw a string with a background (for readability).
pub fn draw_str_bg(text: &str, x: u32, y: u32, fr: u8, fg: u8, fb: u8, br: u8, bg_: u8, bb: u8) {
    let w = (text.len() * GLYPH_WIDTH) as u32;
    framebuffer::fill_rect(x, y, w, GLYPH_HEIGHT as u32, br, bg_, bb);
    draw_str(text, x, y, fr, fg, fb);
}

pub fn init() {
    serial::print_str("[font] 8x16 bitmap font initialized (96 glyphs, ");
    serial::print_hex((FONT_DATA.len()) as u64);
    serial::print_str(" bytes)\n");
}

